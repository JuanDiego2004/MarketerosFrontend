import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

test("Supabase: RLS por empresa, filtros, referencias sin duplicación y revocación", async () => {
  const db = new PGlite();
  const migracion = (n) =>
    readFile(
      new URL(
        `../../MarketerosAgenciaBackend/src/main/resources/sql/crm-v${n}.sql`,
        import.meta.url,
      ),
      "utf8",
    );
  try {
    await db.exec(`
      create role authenticated; create role anon;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
      grant usage on schema auth to authenticated;
      create table rol(id_rol bigint generated by default as identity(start with 10) primary key,nombre_rol text,descripcion text);
      create table usuario(id_usuario bigint primary key,id_rol bigint references rol,id_supabase uuid unique,estado text,nombres text);
      create table cliente(id_cliente bigint generated by default as identity primary key,nombre varchar(150) not null,correo varchar(150),telefono varchar(20),estado text,created_at timestamptz default now(),updated_at timestamptz default now());
      create table campana(id_campana bigint primary key,nombre text,id_cliente bigint references cliente);
      create table permiso(id_permiso bigint generated always as identity primary key,codigo text unique,descripcion text,modulo text);
      create table rol_permiso(id_rol bigint references rol,id_permiso bigint references permiso,primary key(id_rol,id_permiso));
      insert into rol values(1,'Administrador',''),(2,'Líder',''),(3,'Analista','');
      insert into usuario values(1,1,'00000000-0000-0000-0000-000000000001','ACTIVO','Agencia');
    `);
    for (let n = 1; n <= 14; n++) await db.exec(await migracion(n));
    await db.exec(await migracion(14));
    await db.exec(`
      insert into cliente(id_cliente,nombre) values(1,'Andina'),(2,'Ajena');
      -- La migración v9 ya crea la ficha CRM al insertar el cliente canónico.
      insert into usuario select 2,id_rol,'00000000-0000-0000-0000-000000000002','ACTIVO','Cliente Andina' from rol where nombre_rol='Cliente';
      insert into usuario select 3,id_rol,'00000000-0000-0000-0000-000000000003','ACTIVO','Cliente Ajena' from rol where nombre_rol='Cliente';
      insert into crm_portal_acceso(usuario_id,empresa_id,otorgado_por) values(2,1,1),(3,2,1);
      insert into crm_acuerdo(id,tipo,empresa_id,nombre,servicio,modalidad,desde,hasta,moneda,honorarios,presupuesto,produccion,responsable_id,alcance,plataformas,frecuencia,estado) overriding system value
      values(1,'CONTRATO',1,'Integral Andina','INTEGRAL','PAGADA','2026-01-01','2026-12-31','PEN',500,1000,200,1,'Campañas','META','MENSUAL','ACTIVO'),
        (2,'CONTRATO',1,'Análisis Andina','ANALISIS','PAGADA','2026-01-01','2026-12-31','PEN',500,0,0,1,'Análisis','META','MENSUAL','ACTIVO'),
        (3,'CONTRATO',2,'Ajeno','INTEGRAL','PAGADA','2026-01-01','2026-12-31','USD',500,1000,200,1,'Otro','GOOGLE','MENSUAL','ACTIVO'),
        (4,'CONTRATO',1,'Borrador privado','ANALISIS','PAGADA','2026-01-01','2026-12-31','PEN',500,0,0,1,'Pendiente','META','MENSUAL','BORRADOR');
      insert into campana values(1,'Lanzamiento Andina',1),(2,'Campaña ajena',2),(3,'Campaña borrador',1);
      insert into crm_acuerdo_campana values(1,1),(3,2),(4,3);
      insert into crm_cuenta_publicitaria(id,empresa_id,nombre,codigo,plataforma,moneda) overriding system value values(1,1,'Meta Andina','A1','META','PEN'),(2,1,'Google Andina','A2','GOOGLE','USD'),(3,2,'Ajena','A3','META','USD');
      insert into crm_anuncio(id,contrato_id,cuenta_id,campana_id,codigo,nombre,formato,fecha) overriding system value values
        (1,1,1,1,'AD1','Video Andina','VIDEO','2026-11-01'),(2,1,2,1,'AD2','Imagen Andina','IMAGEN','2026-11-01'),
        (3,3,3,2,'AD3','Ajeno','VIDEO','2026-11-01'),(4,4,1,3,'AD4','Borrador','TEXTO','2026-11-01'),
        (5,1,3,1,'AD5','Cuenta de otra empresa','TEXTO','2026-11-01');
      insert into crm_contrato_anuncio values(1,1,'CREADO'),(2,1,'REFERENCIA'),(1,2,'CREADO'),(3,3,'CREADO'),(2,3,'REFERENCIA');
      insert into crm_anuncio_metrica values(1,'2026-11-01','PE',1000,100,10,20,200),(1,'2026-11-02','CO',2000,100,5,30,100),
        (2,'2026-11-01','PE',500,10,1,5,15),(3,'2026-11-01','US',9000,900,90,900,9000),
        (4,'2026-11-01','PE',100,1,0,1,0),(5,'2026-11-01','PE',50000,1,0,1,0);
      -- Un permiso antiguo demasiado amplio no debe saltarse el guardián restrictivo.
      create policy legado_permisivo on crm_anuncio_metrica for select to authenticated using(true);
      grant select on crm_anuncio_metrica to anon;
      create policy anon_antiguo on crm_anuncio_metrica for select to anon using(true);
    `);
    async function usuario(id) {
      await db.exec(
        `reset role; select set_config('request.jwt.claim.sub','00000000-0000-0000-0000-${String(id).padStart(12, "0")}',false); set role authenticated;`,
      );
    }
    async function consulta(extra = "") {
      return (
        await db.query(
          `select crm_portal_estadisticas(p_desde=>'2026-11-01',p_hasta=>'2026-11-03'${extra}) datos`,
        )
      ).rows[0].datos;
    }
    // El portal operativo usa JDBC: probar su SQL real como propietario, sin ayuda de RLS.
    const entrega = await readFile(
      new URL(
        "../../MarketerosAgenciaBackend/src/main/java/com/marketing/agencia/crm/CrmEntregaServicio.java",
        import.meta.url,
      ),
      "utf8",
    );
    const contexto = entrega.match(/ANUNCIOS_PORTAL = """([\s\S]*?)"""/)[1];
    assert.deepEqual(
      (
        await db.query(
          "select a.id " + contexto + " where visible.id=$1 order by a.id",
          [1],
        )
      ).rows.map((r) => r.id),
      [1, 2],
    );
    assert.deepEqual(
      (
        await db.query(
          "select a.id " + contexto + " where visible.id=$1 order by a.id",
          [2],
        )
      ).rows.map((r) => r.id),
      [1],
    );
    assert.equal(
      (
        await db.query(
          "select sum(m.inversion)::float8 total " +
            contexto +
            " join crm_anuncio_metrica m on m.anuncio_id=a.id where visible.id=$1 and cuenta.moneda=visible.moneda",
          [1],
        )
      ).rows[0].total,
      50,
    );
    await usuario(2);
    const todos = await consulta();
    assert.equal(todos.empresa.nombre, "Andina");
    assert.equal(todos.simulado, true);
    assert.equal(todos.retornoVerificado, false);
    assert.deepEqual(todos.contratos.map((c) => c.id).sort(), [1, 2]);
    assert.deepEqual(
      todos.campanas.map((c) => c.id),
      [1],
    );
    assert.equal(
      todos.registros.reduce((n, r) => n + r.impresiones, 0),
      3500,
    );
    assert.equal(
      (await db.query("select count(*)::int n from crm_anuncio_metrica"))
        .rows[0].n,
      3,
    );
    for (const [tabla, col, esperado] of [
      ["crm_acuerdo", "id", [1, 2]],
      ["crm_cuenta", "id", [1]],
      ["crm_anuncio", "id", [1, 2]],
      ["campana", "id_campana", [1]],
    ])
      assert.deepEqual(
        (
          await db.query(`select ${col} id from ${tabla} order by ${col}`)
        ).rows.map((r) => r.id),
        esperado,
      );
    assert.equal(
      (await consulta(",p_contrato=>2")).registros.reduce(
        (n, r) => n + r.impresiones,
        0,
      ),
      3000,
    );
    assert.equal(
      (
        await consulta(
          ",p_pais=>'PE',p_plataforma=>'META',p_moneda=>'PEN',p_campana=>1",
        )
      ).registros[0].impresiones,
      1000,
    );
    assert.equal(
      (await consulta(",p_busqueda=>'Imagen'")).registros[0].moneda,
      "USD",
    );
    assert.equal((await consulta(",p_busqueda=>'%'")).registros.length, 0);
    assert.equal((await consulta(",p_pais=>'US'")).registros.length, 0);
    assert.equal((await consulta(",p_busqueda=>'Análisis'")).registros.reduce((n,r)=>n+r.impresiones,0),3000);
    assert.equal((await consulta(",p_contrato=>1,p_busqueda=>'Análisis'")).registros.length,0);
    await assert.rejects(consulta(",p_contrato=>3"), (e) => e.code === "42501");
    await assert.rejects(consulta(",p_campana=>2"), (e) => e.code === "42501");
    await assert.rejects(
      db.query("select crm_portal_estadisticas('2026-12-01','2026-11-01')"),
      (e) => e.code === "22023",
    );
    await assert.rejects(
      db.exec("update crm_anuncio_metrica set inversion=0"),
      (e) => e.code === "42501",
    );
    await db.exec(
      "reset role; grant update,insert,delete on crm_anuncio_metrica to authenticated; create policy escritura_antigua on crm_anuncio_metrica for all to authenticated using(true) with check(true); set role authenticated",
    );
    assert.equal(
      (
        await db.query(
          "update crm_anuncio_metrica set inversion=0 returning anuncio_id",
        )
      ).rows.length,
      0,
    );
    assert.equal(
      (await db.query("delete from crm_anuncio_metrica returning anuncio_id"))
        .rows.length,
      0,
    );
    await assert.rejects(
      db.query(
        "insert into crm_anuncio_metrica values(1,'2026-11-03','PE',1,0,0,0,0)",
      ),
      (e) => e.code === "42501",
    );
    await usuario(3);
    assert.equal((await consulta()).empresa.nombre, "Ajena");
    assert.equal((await consulta()).registros[0].impresiones, 9000);
    await usuario(1);
    await assert.rejects(consulta(), (e) => e.code === "42501");
    await db.exec(
      "reset role; update crm_portal_acceso set activo=false where usuario_id=2",
    );
    await usuario(2);
    await assert.rejects(consulta(), (e) => e.code === "42501");
    assert.equal(
      (await db.query("select count(*)::int n from crm_anuncio_metrica"))
        .rows[0].n,
      0,
    );
    await db.exec("reset role; set role anon");
    await assert.rejects(consulta(), (e) => e.code === "42501");
    await assert.rejects(
      db.query("select * from crm_anuncio_metrica"),
      (e) => e.code === "42501",
    );
  } finally {
    await db.close();
  }
});
