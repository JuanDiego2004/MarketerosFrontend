import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";

// Base PostgreSQL aislada: valida las migraciones, no reemplaza el inventario de Supabase.
test("migraciones CRM, FK, deduplicación, permisos y reserva idempotente", async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create table public.rol(id_rol bigint generated by default as identity (start with 10) primary key,nombre_rol text,descripcion text);
      create table public.usuario(id_usuario bigint primary key,id_rol bigint references rol,id_supabase uuid,estado text,nombres text);
      create table public.cliente(id_cliente bigint generated by default as identity primary key,nombre varchar(150) not null,correo varchar(150),telefono varchar(20),estado text,created_at timestamptz not null default now(),updated_at timestamptz not null default now());
      create table public.campana(id_campana bigint primary key,nombre text,id_cliente bigint references cliente);
      create table public.permiso(id_permiso bigint generated always as identity primary key,codigo text unique,descripcion text,modulo text);
      create table public.rol_permiso(id_rol bigint references rol,id_permiso bigint references permiso,primary key(id_rol,id_permiso));
      insert into rol(id_rol,nombre_rol) values(1,'Administrador'),(2,'Líder'),(3,'Analista');
      insert into usuario values(1,1,'00000000-0000-0000-0000-000000000001','ACTIVO','Admin');
      insert into campana(id_campana,nombre) values(1,'Campaña de prueba');
    `);
    for (const nombre of ["crm-v1.sql", "crm-v2.sql"])
      await db.exec(
        await readFile(
          new URL(
            `../../backend_agencia/src/main/resources/sql/${nombre}`,
            import.meta.url,
          ),
          "utf8",
        ),
      );
    await db.exec(`insert into crm_contacto(id,nombre,correo,estado,origen,etiquetas,responsable_id,campana_id) overriding system value values(100,'Anterior','anterior@example.test','NUEVO','WEB',' Premium ,premium,Antigua',1,1);
      insert into crm_oportunidad(id,nombre,contacto_id,etapa_id,responsable_id,valor,probabilidad,fecha_cierre) overriding system value values(100,'Anterior',100,1,1,100,0,current_date)`);
    await db.exec(
      await readFile(
        new URL(
          "../../backend_agencia/src/main/resources/sql/crm-v3.sql",
          import.meta.url,
        ),
        "utf8",
      ),
    );
    assert.equal(
      (await db.query("select etiquetas from crm_contacto where id=100"))
        .rows[0].etiquetas,
      " Premium ,premium,Antigua",
    );
    assert.equal(
      (
        await db.query(
          "select count(*)::int n from crm_contacto_etiqueta where contacto_id=100",
        )
      ).rows[0].n,
      2,
    );
    assert.equal(
      (
        await db.query(
          "select count(*)::int n from crm_transicion where oportunidad_id=100 and linea_base",
        )
      ).rows[0].n,
      1,
    );
    await db.exec("update crm_contacto set etiquetas='nueva' where id=100");
    assert.equal(
      (
        await db.query(
          "select count(*)::int n from crm_contacto_etiqueta where contacto_id=100",
        )
      ).rows[0].n,
      1,
    );
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v4.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v5.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v6.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v7.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v8.sql',import.meta.url),'utf8'));
    await db.exec(`insert into cliente(id_cliente,nombre,estado) values(100,'Empresa principal','ACTIVO'),(101,'Empresa sin ficha','ACTIVO');
      update campana set id_cliente=100 where id_campana=1;
      insert into crm_cuenta(nombre,cliente_id) values('Perfil principal',100),('Perfil secundario',100),('Independiente',null);
      update crm_contacto set cuenta_id=2 where id=100;
      insert into crm_nota(cuenta_id,texto,autor_id) values(2,'Nota conservada',1);
      insert into crm_archivo(cuenta_id,nombre,contenido,autor_id) values(2,'conservado.txt',decode('4142','hex'),1);`);
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v9.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v10.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v11.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v12.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../../backend_agencia/src/main/resources/sql/crm-v13.sql',import.meta.url),'utf8'));
    assert.equal((await db.query('select count(*)::int n from crm_servicio')).rows[0].n,3);
    await assert.rejects(db.exec("insert into crm_anuncio(contrato_id,cuenta_id,campana_id,codigo,nombre,formato,fecha) values(999,999,1,'INEXISTENTE','Sin relación','VIDEO',current_date)"));
    assert.equal((await db.query("select cuenta_id from crm_contacto where id=100")).rows[0].cuenta_id, 1);
    assert.equal((await db.query("select cuenta_id from crm_nota where texto='Nota conservada'")).rows[0].cuenta_id, 1);
    assert.equal((await db.query("select encode(contenido,'hex') contenido from crm_archivo where nombre='conservado.txt'")).rows[0].contenido, '4142');
    assert.equal((await db.query("select fusionada_en from crm_cuenta where id=2")).rows[0].fusionada_en, 1);
    assert.equal((await db.query("select datos->>'nombre' nombre from crm_empresa_migracion where tipo='cuenta' and registro_id=2")).rows[0].nombre,'Perfil secundario');
    assert.equal((await db.query("select count(*)::int n from cliente c left join crm_cuenta a on a.cliente_id=c.id_cliente and a.fusionada_en is null where a.id is null")).rows[0].n,0);
    await db.exec("insert into cliente(nombre,estado) values('Cliente desde API anterior','ACTIVO')");
    assert.equal((await db.query("select count(*)::int n from crm_cuenta where nombre='Cliente desde API anterior'")).rows[0].n,1);
    await db.exec("update cliente set nombre='Nombre actualizado' where id_cliente=100");
    assert.equal((await db.query("select nombre from crm_cuenta where id=1")).rows[0].nombre,'Nombre actualizado');
    await db.exec("update crm_cuenta set nombre='Nombre desde CRM' where id=1");
    assert.equal((await db.query("select nombre from cliente where id_cliente=100")).rows[0].nombre,'Nombre desde CRM');
    await assert.rejects(db.exec("insert into crm_cuenta(nombre,cliente_id) values('Duplicado',100)"));
    const roles = await db.query(
      `select r.nombre_rol,p.codigo from rol_permiso rp join rol r using(id_rol) join permiso p using(id_permiso)`,
    );
    assert(
      roles.rows.some(
        (r) =>
          r.nombre_rol === "Analista" &&
          r.codigo === "CRM_ACTIVIDADES_GESTIONAR",
      ),
    );
    assert(
      !roles.rows.some(
        (r) =>
          r.nombre_rol === "Analista" && r.codigo === "CRM_PIPELINE_GESTIONAR",
      ),
    );
    assert(
      !roles.rows.some(
        (r) =>
          r.nombre_rol === "Líder" &&
          r.codigo === "CRM_INTEGRACIONES_GESTIONAR",
      ),
    );
    await db.exec(
      `insert into crm_contacto(nombre,correo,estado,origen,responsable_id,campana_id) values('Prueba','persona@example.test','NUEVO','WEB',1,1)`,
    );
    await assert.rejects(
      db.exec(
        `insert into crm_contacto(nombre,correo,estado,origen,responsable_id) values('Duplicado','PERSONA@example.test','NUEVO','WEB',1)`,
      ),
    );
    await db.exec(
      `insert into crm_oportunidad(nombre,contacto_id,etapa_id,responsable_id,valor,probabilidad,fecha_cierre) values('Venta',1,4,1,120,100,current_date)`,
    );
    await assert.rejects(
      db.exec(
        `insert into crm_actividad(nombre,tipo,estado,fecha,responsable_id) values('Sin relación','LLAMADA','PENDIENTE',now(),1)`,
      ),
    );
    await db.exec(`insert into crm_segmento(nombre,etiqueta) values('Segmento','premium');
      insert into crm_automatizacion(nombre,segmento_id,accion,asunto,activa,autor_id) values('Bienvenida',1,'CREAR_TAREA','Llamar',true,1);
      insert into crm_ejecucion(automatizacion_id,contacto_id,estado) values(1,1,'PENDIENTE') on conflict do nothing;
      insert into crm_ejecucion(automatizacion_id,contacto_id,estado) values(1,1,'PENDIENTE') on conflict do nothing;`);
    assert.equal(
      (await db.query("select count(*)::int cantidad from crm_ejecucion"))
        .rows[0].cantidad,
      1,
    );
    assert.equal(
      (
        await db.query(
          "select count(*)::int cantidad from pg_class where relname like 'crm_%' and relkind='r' and relrowsecurity",
        )
      ).rows[0].cantidad,
      59,
    );
    await db.exec("delete from crm_contacto where id=1");
    assert.equal(
      (
        await db.query(
          "select count(*)::int cantidad from crm_oportunidad where contacto_id=1",
        )
      ).rows[0].cantidad,
      0,
    );
  } finally {
    await db.close();
  }
});
